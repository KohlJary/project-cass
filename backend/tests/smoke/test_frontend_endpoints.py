def _pattern(path):
    """Regex for a path where any {placeholder} matches one segment."""
    return re.compile("^" + re.sub(r"\\\{[^}]*\\\}", "[^/]+", re.escape(path)) + "$")


@pytest.fixture(scope="module")
def route_table():
    """(METHOD, path) pairs the app serves, plus WebSocket paths as 'WS'."""
    import main_sdk

    routes = {(m.upper(), p) for p, ops in main_sdk.app.openapi()["paths"].items() for m in ops}
    routes.add(("WS", "/ws"))
    return routes


def _route_exists(routes, method, path):
    # Match both ways: a frontend {param} can fill a literal backend segment
    # (e.g. .../pending/{id}/{action} -> .../pending/{edge_id}/accept), and a
    # backend {param} matches any frontend literal.
    front = _pattern(path)
    for route_method, route_path in routes:
        if route_method != method:
            continue
        if front.match(route_path) or _pattern(route_path).match(path.replace("{param}", "x")):
            return True
    return False


def _params():
    for e in ENDPOINTS:
        key = f"{e['method']} {e['path']}"
        marks = []
        if key in KNOWN_MISSING:
            marks.append(pytest.mark.xfail(strict=True, reason=KNOWN_MISSING[key]))
        yield pytest.param(e, id=f"{e['frontend']}:{key}", marks=marks)


def test_fixture_is_up_to_date():
    """The committed fixture matches what the extractor finds in the frontends today."""
    import importlib.util

    script = Path(__file__).resolve().parents[2] / "scripts" / "extract_frontend_endpoints.py"
    spec = importlib.util.spec_from_file_location("extract_frontend_endpoints", script)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    assert module.render(module.extract()) == FIXTURE.read_text(), (
        "frontend calls changed: run `python scripts/extract_frontend_endpoints.py` and commit the fixture")


def test_fixture_covers_every_frontend():
    frontends = {e["frontend"] for e in ENDPOINTS}
    assert frontends == {"admin-frontend", "mobile-frontend", "tui-frontend", "godot-frontend"}


def test_known_missing_entries_are_still_called():
    called = {f"{e['method']} {e['path']}" for e in ENDPOINTS}
    assert set(KNOWN_MISSING) <= called, set(KNOWN_MISSING) - called


@pytest.mark.parametrize("endpoint", list(_params()))
def test_frontend_endpoint_exists(endpoint, route_table):
    assert _route_exists(route_table, endpoint["method"], endpoint["path"]), (
        f"{endpoint['method']} {endpoint['path']} called from {endpoint['sources'][0]} has no route")
