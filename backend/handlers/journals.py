"""
Journal tool handler - manages journal entries
"""
from typing import Dict

from memory.journals import is_daily_journal


def _recent_daily(memory, n: int):
    """Her recent daily journals, newest first (a memory without daily_only: all)."""
    try:
        return memory.get_recent_journals(n=n, daily_only=True)
    except TypeError:
        return memory.get_recent_journals(n=n)


async def execute_journal_tool(
    tool_name: str,
    tool_input: Dict,
    memory
) -> Dict:
    """
    Execute a journal tool.

    Args:
        tool_name: Name of the tool to execute
        tool_input: Input parameters for the tool
        memory: CassMemory instance

    Returns:
        Dict with 'success', 'result', and optionally 'error'
    """
    try:
        if tool_name == "recall_journal":
            date = tool_input.get("date")

            if date:
                # Her daily journal for that date. Research, spell and world
                # journals share dates; this used to return whichever Chroma
                # listed first, so a search pointing at a day's journal about
                # Kohl could open a research summary instead.
                daily = (memory.get_daily_journal_entry(date)
                         if hasattr(memory, "get_daily_journal_entry") else None)
                journal = daily or memory.get_journal_entry(date)
                if journal and not daily and hasattr(memory, "get_daily_journal_entry"):
                    # No daily journal for the date (today's isn't written until
                    # tonight): say what this one is, so a research summary dated
                    # today doesn't read as her day (2026-11-18).
                    kind = (journal.get("metadata") or {}).get("journal_type") or "research or spell"
                    return {
                        "success": True,
                        "result": (f"No daily journal for {date} yet (each day's is written that night). "
                                   f"There is a {kind} journal from that date, not about my day:\n\n"
                                   f"{journal['content']}")
                    }
                if not journal:
                    return {
                        "success": True,
                        "result": f"No journal entry found for {date}. You may not have journaled that day, or the journal hasn't been generated yet."
                    }

                return {
                    "success": True,
                    "result": f"# Journal Entry - {date}\n\n{journal['content']}\n\n---\n*Written: {journal['metadata'].get('timestamp', 'unknown')}*"
                }
            else:
                # Her most recent daily journal. Research, spell and world journals
                # share type=journal; "most recent" used to be whichever had the latest
                # date, so a research summary read as her journal (2026-11-18).
                journals = _recent_daily(memory, 1)
                if not journals:
                    return {
                        "success": True,
                        "result": "No daily journal yet. Today's is written tonight, from today's conversations and sessions."
                    }

                journal = journals[0]
                date = journal["metadata"].get("journal_date", "unknown")
                return {
                    "success": True,
                    "result": f"# Most Recent Journal - {date}\n\n{journal['content']}\n\n---\n*Written: {journal['metadata'].get('timestamp', 'unknown')}*"
                }

        elif tool_name == "list_journals":
            limit = tool_input.get("limit", 10)
            journals = _recent_daily(memory, limit)

            if not journals:
                return {
                    "success": True,
                    "result": "No journal entries found yet."
                }

            # Return summaries (pre-generated by local LLM) or fallback to excerpt
            journal_list = []
            for j in journals:
                date = j["metadata"].get("journal_date", "unknown")
                summary = j["metadata"].get("summary")
                if not summary:
                    # Fallback for journals without summaries
                    content = j["content"]
                    summary = content[:300] + "..." if len(content) > 300 else content
                journal_list.append(f"**{date}**: {summary}")

            return {
                "success": True,
                "result": f"Found {len(journals)} journal(s):\n\n" + "\n\n".join(journal_list) + "\n\n*Use recall_journal with a specific date for full content.*"
            }

        elif tool_name == "search_journals":
            query = tool_input["query"]
            limit = tool_input.get("limit", 5)

            # Use semantic search on journal type
            results = memory.collection.query(
                query_texts=[query],
                n_results=limit,
                where={"type": "journal"}
            )

            if not results["documents"] or not results["documents"][0]:
                return {
                    "success": True,
                    "result": f"No journal entries found matching '{query}'."
                }

            # Return summaries (pre-generated by local LLM) or fallback to excerpt
            result_lines = [f"Found {len(results['documents'][0])} journal(s) matching '{query}':\n"]
            for i, doc in enumerate(results["documents"][0]):
                metadata = results["metadatas"][0][i] if results["metadatas"] else {}
                date = metadata.get("journal_date", "unknown")
                distance = results["distances"][0][i] if results["distances"] else 1.0
                relevance_pct = int(max(0, 1 - distance) * 100)

                # Use pre-generated summary if available, otherwise excerpt
                summary = metadata.get("summary")
                if not summary:
                    summary = doc[:300] + "..." if len(doc) > 300 else doc
                kind = "" if is_daily_journal(metadata or {}) else (
                    f" [{metadata.get('journal_type') or 'research or spell'} journal, not my daily journal]")

                result_lines.append(f"**{date}**{kind} ({relevance_pct}% relevant): {summary}")

            return {
                "success": True,
                "result": "\n\n".join(result_lines) + "\n\n*Use recall_journal with a specific date for full content.*"
            }

        else:
            return {"success": False, "error": f"Unknown journal tool: {tool_name}"}

    except Exception as e:
        return {"success": False, "error": str(e)}
